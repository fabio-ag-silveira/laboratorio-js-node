/**
 * O banco de exemplo da trilha de PostgreSQL: monitoramento de pragas em usinas.
 *
 *     usinas ──< talhoes ──< armadilhas ──< capturas ──< deteccoes
 *        └────< tecnicos ───────────────────────┘
 *
 * Os dados são GERADOS por SQL, com aritmética modular em vez de `random()`:
 * toda instalação produz exatamente as mesmas linhas, e os números citados nas
 * lições batem. Há irregularidades de propósito, porque são elas que ensinam:
 * uma usina sem talhões, um técnico sem usina, um talhão sem variedade,
 * armadilhas desativadas, semanas sem leitura, metadados incompletos.
 */

export const ESQUEMA = `
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TYPE situacao_captura AS ENUM ('pendente', 'processada', 'rejeitada');

CREATE TABLE usinas (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome   text    NOT NULL UNIQUE,
  uf     char(2) NOT NULL,
  ativa  boolean NOT NULL DEFAULT true
);

CREATE TABLE talhoes (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usina_id  integer NOT NULL REFERENCES usinas (id),
  codigo    text    NOT NULL,
  area_ha   numeric(7,2) NOT NULL CHECK (area_ha > 0),
  variedade text,
  UNIQUE (usina_id, codigo)
);

CREATE TABLE tecnicos (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome      text NOT NULL,
  email     text NOT NULL UNIQUE,
  usina_id  integer REFERENCES usinas (id)
);

CREATE TABLE armadilhas (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  talhao_id    integer NOT NULL REFERENCES talhoes (id),
  codigo       text    NOT NULL UNIQUE,
  tipo         text    NOT NULL CHECK (tipo IN ('adesiva amarela', 'adesiva azul', 'feromônio')),
  instalada_em date    NOT NULL,
  ativa        boolean NOT NULL DEFAULT true
);

CREATE TABLE capturas (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  armadilha_id  integer NOT NULL REFERENCES armadilhas (id),
  tecnico_id    integer REFERENCES tecnicos (id),
  capturada_em  timestamptz NOT NULL,
  situacao      situacao_captura NOT NULL DEFAULT 'pendente',
  metadados     jsonb NOT NULL DEFAULT '{}'
);

CREATE TABLE deteccoes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  captura_id  bigint NOT NULL REFERENCES capturas (id) ON DELETE CASCADE,
  classe      text   NOT NULL,
  confianca   real   NOT NULL CHECK (confianca BETWEEN 0 AND 1),
  x           integer NOT NULL,
  y           integer NOT NULL,
  largura     integer NOT NULL,
  altura      integer NOT NULL
);
`;

